//! `field::process(Processors::*)`: runs one step of a unit.

use crate::duel::Duel;
use crate::processor1::ExecKind;
use crate::units::Unit;

impl Duel {
    /// Queues a unit (`emplace_process`): it runs before the current unit's next step.
    pub fn emplace_process<U: Into<Unit>>(&mut self, u: U) {
        self.core.subunits.push_back(u.into());
    }

    /// Runs the current step of `unit`: `true` when the unit is done.
    pub fn process_unit(&mut self, unit: &mut Unit) -> bool {
        match unit {
            Unit::Adjust(a) => self.process_adjust(a),
            Unit::Turn(a) => self.process_turn(a),
            Unit::RefreshLoc(a) => self.process_refresh_loc(a),
            Unit::Startup(a) => self.process_startup(a),
            Unit::SelectBattleCmd(a) => self.process_select_battle_cmd(a),
            Unit::SelectIdleCmd(a) => self.process_select_idle_cmd(a),
            Unit::SelectEffectYesNo(a) => self.process_select_effect_yes_no(a),
            Unit::SelectYesNo(a) => self.process_select_yes_no(a),
            Unit::SelectOption(a) => self.process_select_option(a),
            Unit::SelectCard(a) => self.process_select_card(a),
            Unit::SelectCardCodes(a) => self.process_select_card_codes(a),
            Unit::SelectUnselectCard(a) => self.process_select_unselect_card(a),
            Unit::SelectChain(a) => self.process_select_chain(a),
            Unit::SelectPlace(a) => self.process_select_place(a),
            Unit::SelectPosition(a) => self.process_select_position(a),
            Unit::SelectTributeP(a) => self.process_select_tribute_p(a),
            Unit::SortChain(a) => self.process_sort_chain(a),
            Unit::SelectCounter(a) => self.process_select_counter(a),
            Unit::SelectSum(a) => self.process_select_sum(a),
            Unit::SortCard(a) => self.process_sort_card(a),
            Unit::SelectRelease(a) => self.process_select_release(a),
            Unit::SelectTribute(a) => self.process_select_tribute(a),
            Unit::QuickEffect(a) => self.process_quick_effect(a),
            Unit::IdleCommand(a) => self.process_idle_command(a),
            Unit::PhaseEvent(a) => self.process_phase_event(a),
            Unit::PointEvent(a) => self.process_point_event(a),
            Unit::BattleCommand(a) => self.process_battle_command(a),
            Unit::DamageStep(a) => self.process_damage_step(a),
            Unit::ForcedBattle(a) => self.process_forced_battle(a),
            Unit::AddChain(a) => self.process_add_chain(a),
            Unit::SolveChain(a) => self.process_solve_chain(a),
            Unit::SolveContinuous(a) => self.process_solve_continuous(a),
            Unit::ExecuteCost(a) => self.process_execute(ExecKind::Cost, a.triggering_effect, a.triggering_player, &mut a.shuffle_check_was_disabled),
            Unit::ExecuteOperation(a) => self.process_execute(ExecKind::Operation, a.triggering_effect, a.triggering_player, &mut a.shuffle_check_was_disabled),
            Unit::ExecuteTarget(a) => self.process_execute(ExecKind::Target, a.triggering_effect, a.triggering_player, &mut a.shuffle_check_was_disabled),
            Unit::Destroy(a) => self.process_destroy(a),
            Unit::Release(a) => self.process_release(a),
            Unit::SendTo(a) => self.process_send_to(a),
            Unit::DestroyReplace(a) => self.process_destroy_replace(a),
            Unit::ReleaseReplace(a) => self.process_release_replace(a),
            Unit::SendToReplace(a) => self.process_send_to_replace(a),
            Unit::MoveToField(a) => self.process_move_to_field(a),
            Unit::ChangePos(a) => self.process_change_pos(a),
            Unit::OperationReplace(a) => self.process_operation_replace(a),
            Unit::ActivateEffect(a) => self.process_activate_effect(a),
            Unit::SummonRule(a) => self.process_summon_rule(a),
            Unit::SpSummonRule(a) => self.process_spsummon_rule(a),
            Unit::SpSummon(a) => self.process_spsummon(a),
            Unit::FlipSummon(a) => self.process_flip_summon(a),
            Unit::MonsterSet(a) => self.process_monster_set(a),
            Unit::SpellSet(a) => self.process_spell_set(a),
            Unit::SpSummonStep(a) => self.process_spsummon_step(a),
            Unit::SpellSetGroup(a) => self.process_spell_set_group(a),
            Unit::SpSummonRuleGroup(a) => self.process_spsummon_rule_group(a),
            Unit::Draw(a) => self.process_draw(a),
            Unit::Damage(a) => self.process_damage(a),
            Unit::Recover(a) => self.process_recover(a),
            Unit::Equip(a) => self.process_equip(a),
            Unit::GetControl(a) => self.process_get_control(a),
            Unit::SwapControl(a) => self.process_swap_control(a),
            Unit::ControlAdjust(a) => self.process_control_adjust(a),
            Unit::SelfDestroyUnique(a) => self.process_self_destroy_unique(a),
            Unit::SelfDestroy(a) => self.process_self_destroy(a),
            Unit::SelfToGrave(a) => self.process_self_to_grave(a),
            Unit::TrapMonsterAdjust(a) => self.process_trap_monster_adjust(a),
            Unit::PayLPCost(a) => self.process_pay_lp_cost(a),
            Unit::RemoveCounter(a) => self.process_remove_counter(a),
            Unit::AttackDisable(a) => self.process_attack_disable(a),
            Unit::AnnounceRace(a) => self.process_announce_race(a),
            Unit::AnnounceAttribute(a) => self.process_announce_attribute(a),
            Unit::AnnounceCard(a) => self.process_announce_card(a),
            Unit::AnnounceNumber(a) => self.process_announce_number(a),
            Unit::TossCoin(a) => self.process_toss_coin(a),
            Unit::TossDice(a) => self.process_toss_dice(a),
            Unit::RockPaperScissors(a) => self.process_rock_paper_scissors(a),
            Unit::SelectFusion(a) => self.process_select_fusion(a),
            Unit::DiscardHand(a) => self.process_discard_hand(a),
            Unit::DiscardDeck(a) => self.process_discard_deck(a),
            Unit::SortDeck(a) => self.process_sort_deck(a),
            Unit::RemoveOverlay(a) => self.process_remove_overlay(a),
            Unit::XyzOverlay(a) => self.process_xyz_overlay(a),
            Unit::RefreshRelay(a) => self.process_refresh_relay(a),
        }
    }
}
