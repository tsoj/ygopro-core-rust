"""Generates ygo-core/src/constants.rs from the #defines and flag enums of ygopro-core's headers.

  python3 tools/gen_constants.py target/oracle/src > ygo-core/src/constants.rs
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
DEFINE = re.compile(r"^\s*#define\s+([A-Z][A-Z0-9_]*)\s+(.+?)\s*(?://.*|/\*.*)?$")
ENUM_ITEM = re.compile(r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*([^,/]+?)\s*,?\s*(?://.*)?$")
U64_FAMILIES = ("RACE_", "CATEGORY_", "DUEL_")
SKIP = {"OCG_VERSION_MAJOR", "OCG_VERSION_MINOR", "TRUE", "FALSE", "MAX_VARIANT_TYPES"}

exprs: dict[str, str] = {}
order: list[str] = []
files = sorted(p for p in src.glob("*.h")) + sorted(p for p in src.glob("*.cpp"))
for path in files:
    in_enum = False
    for line in path.read_text(errors="ignore").splitlines():
        if re.match(r"\s*enum\s+(effect_flag|effect_flag2|ActivityType)\b", line):
            in_enum = True
            continue
        if in_enum:
            if "}" in line:
                in_enum = False
                continue
            m = ENUM_ITEM.match(line)
            if m and m.group(1) not in exprs:
                exprs[m.group(1)] = m.group(2)
                order.append(m.group(1))
            continue
        m = DEFINE.match(line)
        if not m or "(" in m.group(1):
            continue
        name, expr = m.groups()
        if name in SKIP or name.endswith("_H") or name.endswith("_H_") or name in exprs:
            continue
        exprs[name] = expr

def value(name: str, depth: int = 0) -> int | None:
    expr = exprs[name]
    expr = re.sub(r"\b(\d+|0x[0-9a-fA-F]+)[uUlL]+\b", r"\1", expr)
    expr = re.sub(r"static_cast<[^>]+>|\((?:uint|int)\d+_t\)", "", expr)
    expr = re.sub(r"\b0([0-7]+)\b", r"0o\1", expr)  # C octal literals (LINK_MARKER_*)
    def sub(m):
        n = m.group(0)
        if n in exprs and depth < 20:
            v = value(n, depth + 1)
            if v is None:
                raise ValueError
            return str(v)
        raise ValueError
    try:
        py = re.sub(r"\b[A-Z][A-Z0-9_]*\b", sub, expr)
        if not re.fullmatch(r"[\s0-9a-fA-Fxo()|&+\-*<>~]+", py):
            return None
        v = eval(py.replace("~", "~"))
    except Exception:
        return None
    return v if isinstance(v, int) else None

out = ["//! Generated by tools/gen_constants.py from ygopro-core's headers: do not edit.",
       "#![allow(dead_code)]", ""]
for name in list(exprs):
    v = value(name)
    if v is None:
        continue
    if v < 0:
        out.append(f"pub const {name}: i32 = {v};")
    elif v > 0xFFFFFFFF or name.startswith(U64_FAMILIES):
        out.append(f"pub const {name}: u64 = {v:#x};")
    else:
        out.append(f"pub const {name}: u32 = {v:#x};")
print("\n".join(out))
