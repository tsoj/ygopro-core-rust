-- Generates ygo-cards/src/constants.rs: every integer global that constant.lua defines (the
-- constants card scripts use), evaluated by Lua itself.
-- usage: lua gen_script_constants.lua <constant.lua> > constants.rs
local before = {}
for k in pairs(_G) do before[k] = true end
Duel = setmetatable({}, { __index = function() return function() end end })
Debug, Card, Effect, Group = Duel, Duel, Duel, Duel
local dir = arg[1]:match("(.*/)") or ""
rawset(Duel, "LoadScript", function(name) dofile(dir .. name) end)
for _, k in ipairs({"Duel", "Debug", "Card", "Effect", "Group"}) do before[k] = true end
dofile(arg[1])
local names = {}
for k, v in pairs(_G) do
	if not before[k] and math.type(v) == "integer" then names[#names + 1] = k end
end
table.sort(names)
print("//! The constants of the card scripts (`constant.lua`), generated by tools/gen_script_constants.lua.")
print("#![allow(dead_code, non_upper_case_globals, clippy::unreadable_literal)]")
print("")
for _, k in ipairs(names) do
	local v = _G[k]
	local t = "i64"
	if v >= 0 and v <= 0xffffffff then t = "u32" elseif v >= 0 then t = "u64" end
	if v < 0 and v >= -0x80000000 then t = "i32" end
	-- (the 64-bit families, as in the core's constants)
	if v >= 0 and (k:match("^RACE_") or k:match("^CATEGORY_") or k:match("^DUEL_")) then t = "u64" end
	if t == "u64" or t == "i64" then
		print(string.format("pub const %s: %s = %d;", k, t, v))
	else
		print(string.format("pub const %s: %s = 0x%x;", k, t, v & (t == "i32" and 0xffffffffffffffff or 0xffffffff)) )
	end
end
